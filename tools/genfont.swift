// Renders anti-aliased bitmap fonts for the 3DS from a TTF with CoreText.
// usage: swift tools/genfont.swift out.c name:font.ttf:size [...]
import CoreGraphics
import CoreText
import Foundation

let codes: [UInt32] = Array(32...126) + [
	0xC4, 0xD6, 0xDC, 0xE4, 0xF6, 0xFC, 0xDF, // Ä Ö Ü ä ö ü ß
	0xB7, 0xD7, 0xB0, 0x2013, 0x2022, 0x2026, // · × ° – • …
	0x2190, 0x2191, 0x2192, 0x2193, 0x2713, // ← ↑ → ↓ ✓
	0x25B2, 0x25B6, 0x25BC, 0x25C0, // ▲ ▶ ▼ ◀
]

var out = "// Generated by tools/genfont.swift from Inter (SIL Open Font License, see fonts/OFL.txt).\n#include \"font.h\"\n\n"

for spec in CommandLine.arguments.dropFirst(2) {
	let parts = spec.split(separator: ":").map(String.init)
	let (name, path, size) = (parts[0], parts[1], CGFloat(Double(parts[2])!))
	let data = try! Data(contentsOf: URL(fileURLWithPath: path))
	let cgFont = CGFont(CGDataProvider(data: data as CFData)!)!
	let font = CTFontCreateWithGraphicsFont(cgFont, size, nil, nil)

	var bitmap = [UInt8]()
	var glyphs = [String]()
	var missing = ""
	for code in codes.sorted() {
		var ch = UniChar(code)
		var glyph = CGGlyph(0)
		if !CTFontGetGlyphsForCharacters(font, &ch, &glyph, 1) || glyph == 0 {
			missing += String(UnicodeScalar(code)!)
			continue
		}
		var advance = CGSize.zero
		CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
		let b = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyph, nil, 1)
		let x0 = Int(floor(b.minX)), x1 = Int(ceil(b.maxX))
		let y0 = Int(floor(b.minY)), y1 = Int(ceil(b.maxY))
		var w = max(0, x1 - x0), h = max(0, y1 - y0)
		if b.isEmpty { w = 0; h = 0 }

		let offset = bitmap.count
		if w > 0 && h > 0 {
			var pixels = [UInt8](repeating: 0, count: w * h)
			let ctx = CGContext(data: &pixels, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
			                    space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
			ctx.setShouldAntialias(true)
			ctx.setShouldSmoothFonts(false)
			ctx.setAllowsFontSubpixelPositioning(false)
			ctx.setFillColor(gray: 1, alpha: 1)
			var pos = CGPoint(x: CGFloat(-x0), y: CGFloat(-y0))
			CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
			bitmap += pixels // memory row 0 is the top row
		}
		// x/y: bitmap top-left relative to the pen on the baseline (y down).
		glyphs.append("\t{0x\(String(code, radix: 16)), \(w), \(h), \(x0), \(-y1), \(Int((advance.width * 16).rounded())), \(offset)},")
	}
	if !missing.isEmpty { FileHandle.standardError.write("\(name): missing \(missing)\n".data(using: .utf8)!) }

	let ascent = Int(CTFontGetAscent(font).rounded()), descent = Int(CTFontGetDescent(font).rounded())
	out += "static const u8 bitmap_\(name)[] = {\n"
	for i in stride(from: 0, to: bitmap.count, by: 24) {
		out += "\t" + bitmap[i..<min(i + 24, bitmap.count)].map { String($0) }.joined(separator: ",") + ",\n"
	}
	out += "};\n\nstatic const Glyph glyphs_\(name)[] = {\n" + glyphs.joined(separator: "\n") + "\n};\n\n"
	out += "const Font \(name) = {glyphs_\(name), \(glyphs.count), bitmap_\(name), \(ascent), \(descent)};\n\n"
}

try! out.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
